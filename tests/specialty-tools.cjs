assert.equal(api.list('ginecologia y obstetricia').length,1);
api.register({id:'qa-table',title:'Tabla de prueba técnica',kind:'table',specialties:['QA'],columns:['Dato'],rows:[['Valor']],source:{title:'Referencia ficticia de prueba',url:'https://example.org/fixture'}});
assert.equal(api.list('QA')[0].id,'qa-table');

const assert=require('node:assert/strict');
const api=require('../tools/specialty-tools.js');
const calculate=(lmp,reference,cycleDays=28)=>api.dueDate({lmp,reference,cycleDays});
assert.deepEqual(calculate('2026-01-01','2026-10-08'),{dueDate:'2026-10-08',weeks:40,days:0,gestationalDays:280,cycleDays:28});
assert.equal(calculate('2024-02-29','2024-03-07').dueDate,'2024-12-05');
assert.equal(calculate('2026-12-31','2027-01-07').dueDate,'2027-10-07');
assert.equal(calculate('2026-01-01','2026-02-01',30).dueDate,'2026-10-10');
assert.equal(calculate('2026-01-01','2026-02-01',30).gestationalDays,29);
assert.equal(calculate('2026-01-01','2026-02-01',26).dueDate,'2026-10-06');
assert.equal(calculate('2026-01-01','2026-02-01',26).gestationalDays,33);
for(const date of ['2026-02-29','2026-04-31','2026-13-01','','1/1/2026'])assert.throws(()=>calculate(date,'2026-10-17'),/fecha válida/);
assert.throws(()=>calculate('2026-10-18','2026-10-17'),/posterior/);
assert.throws(()=>calculate('2024-01-01','2026-10-17'),/0 a 45/);
for(const cycle of ['',0,14,61,28.5,'abc'])assert.throws(()=>calculate('2026-01-01','2026-02-01',cycle),/ciclo/);
